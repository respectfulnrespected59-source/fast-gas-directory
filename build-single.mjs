/*
 * Generate the single-file build: dist/quantus-app.html
 *
 * The multi-file site is the source of truth. This flattens it so the whole
 * directory can be opened from one local file, with no drift: run it after any
 * change to index.html, the stylesheets or the scripts.
 *
 *   node build-single.mjs
 *
 * ES modules cannot be inlined as-is (a classic <script> has no module scope,
 * and file:// blocks module imports), so the two modules are concatenated into
 * one IIFE: `export` keywords are stripped from data.js and the import block is
 * stripped from app.js. data.js imports nothing, which is what makes this safe.
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = dirname(fileURLToPath(import.meta.url));
const read = (...parts) => readFileSync(join(root, ...parts), "utf8");

const html = read("index.html");
const tokens = read("assets", "tokens.css");
const styles = read("assets", "styles.css");
const favicon = read("assets", "favicon.svg");

// --- flatten the two modules into one classic script ---------------------
const data = read("assets", "data.js").replace(/^export\s+/gm, "");
const app = read("assets", "app.js").replace(
  /^import\s*\{[\s\S]*?\}\s*from\s*["']\.\/data\.js["'];\s*$/m,
  ""
);

if (/^\s*import\s/m.test(app) || /^\s*export\s/m.test(data)) {
  throw new Error("An import/export survived flattening - the bundle would break.");
}

const script = "(() => {\n" + data + "\n" + app + "\n})();";

// --- rewrite the document -------------------------------------------------
const faviconHref = "data:image/svg+xml," + encodeURIComponent(favicon);

const replacements = [
  // A single inlined file has no external style or script URLs to allow, but
  // inline ones are now inherent, so the policy has to permit them.
  [
    /<meta http-equiv="Content-Security-Policy"[^>]*>/,
    '<meta http-equiv="Content-Security-Policy" content="default-src \'none\'; ' +
      "script-src 'unsafe-inline'; style-src 'unsafe-inline' https://fonts.googleapis.com; " +
      "font-src https://fonts.gstatic.com; img-src data:; connect-src 'none'; " +
      "form-action 'none'; base-uri 'none'; object-src 'none'\">",
  ],
  [
    /  <link rel="stylesheet" href="assets\/tokens\.css">\n  <link rel="stylesheet" href="assets\/styles\.css">/,
    "  <style>\n" + tokens + "\n" + styles + "\n  </style>",
  ],
  [
    /  <link rel="icon" href="assets\/favicon\.svg" type="image\/svg\+xml">/,
    '  <link rel="icon" href="' + faviconHref + '" type="image/svg+xml">',
  ],
  [
    /  <script type="module" src="assets\/app\.js"><\/script>/,
    "  <script>\n" + script + "\n  </script>",
  ],
];

let out = html;
for (const [pattern, value] of replacements) {
  if (!pattern.test(out)) {
    throw new Error("build-single: pattern not found -> " + pattern);
  }
  out = out.replace(pattern, () => value);
}

out =
  "<!-- Fast Gas - single-file build. Generated by build-single.mjs from the\n" +
  "     multi-file source; edit the source, not this file. -->\n" +
  out;

mkdirSync(join(root, "dist"), { recursive: true });
const target = join(root, "dist", "quantus-app.html");
writeFileSync(target, out, "utf8");

const kb = (Buffer.byteLength(out, "utf8") / 1024).toFixed(1);
console.log("wrote " + target + " (" + kb + " kB)");

if (/assets\/(app|data)\.js|assets\/[a-z]+\.css/.test(out)) {
  throw new Error("build-single: an asset reference survived - the file is not standalone.");
}
console.log("standalone: no remaining asset references.");
